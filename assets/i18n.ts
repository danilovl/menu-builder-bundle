const DICTS: Record<string, Dict> = { en, ru, es, de, fr, zh, ja, pt, it, ar }

const STORAGE_KEY = 'menu-builder.locale'

function detectLocale(): string {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (stored && DICTS[stored]) {
      return stored
    }
  } catch {
    /* localStorage unavailable */
  }
  const nav = (typeof navigator !== 'undefined' ? navigator.language : 'en').slice(0, 2)

  return DICTS[nav] ? nav : 'en'
}

const currentLocale = ref<string>(detectLocale())

export function useI18n() {
  const dict = computed(() => {
    return DICTS[currentLocale.value] ?? en
  })

  function t(key: string, params?: Record<string, string>): string {
    const raw = dict.value[key] ?? en[key] ?? key
    if (!params) {
      return raw
    }

    return raw.replace(/\{(\w+)\}/g, (_, k: string) => {
      return params[k] ?? `{${k}}`
    })
  }

  function setLocale(code: string): void {
    if (!DICTS[code]) {
      return
    }
    currentLocale.value = code
    try {
      localStorage.setItem(STORAGE_KEY, code)
    } catch {
      /* localStorage unavailable */
    }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = code
      document.documentElement.dir = code === 'ar' ? 'rtl' : 'ltr'
    }
  }

  return { t, locale: currentLocale, setLocale, locales: SUPPORTED_LOCALES }
}
